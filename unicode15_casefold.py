def frozen_casefold(value: str) -> str:
    """Apply the frozen Unicode 15 full default case-fold scalar mapping."""
    return "".join(_MAPPINGS.get(ord(character), character) for character in value)


def mapping_sha256() -> str:
    """Return the digest of the canonical sorted mapping serialization."""
    payload = "".join(
        f"{source:06X};{' '.join(f'{ord(char):06X}' for char in target)}\n"
        for source, target in _MAPPING_ROWS
    ).encode("ascii")
    return hashlib.sha256(payload).hexdigest()


def validate_frozen_table() -> None:
    """Fail if the vendored table is incomplete, duplicated, or corrupted."""
    if len(_MAPPING_ROWS) != MAPPING_COUNT or len(_MAPPINGS) != MAPPING_COUNT:
        raise RuntimeError("Unicode 15 case-fold mapping count mismatch")
    if mapping_sha256() != MAPPING_SHA256:
        raise RuntimeError("Unicode 15 case-fold mapping digest mismatch")


